function readLanguage() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return ["kg", "ru", "en"].includes(saved) ? saved : "kg";
  } catch (error) {
    console.error("Could not read the saved interface language.", error);
    return "kg";
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(readLanguage);

  useEffect(() => {
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
      document.documentElement.lang = language;
    } catch (error) {
      console.error("Could not save the selected interface language.", error);
    }
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage(nextLanguage) {
        if (Object.hasOwn(translations, nextLanguage)) {
          setLanguage(nextLanguage);
        }
      },
      t(key) {
        return translations[language][key] ?? translations.ru[key] ?? key;
      },
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider.");
  }
  return context;
}
